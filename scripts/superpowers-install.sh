#!/usr/bin/env bash
# Superpowers installer / updater / verifier for Arena Agent Mode.
#
# Installs the official Superpowers skills by obra (https://github.com/obra/superpowers)
# into this project, following upstream's docs/porting-to-a-new-harness.md:
# the skills are vendored verbatim and the session-start bootstrap is generated
# into AGENTS.md (Shape C, instructions-file), with a harness tool mapping.
#
# Usage:
#   bash scripts/superpowers-install.sh                 # install/update at pinned ref
#   bash scripts/superpowers-install.sh --check         # verify install (no writes)
#   bash scripts/superpowers-install.sh --ref v7.0.0    # pin a different upstream ref
#   bash scripts/superpowers-install.sh --source /path  # use an existing checkout (offline)
#   bash scripts/superpowers-install.sh --no-agents     # skills only, skip AGENTS.md
#
# Updating: re-run with --ref main (or a newer tag) and commit the diff.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
SKILLS_DIR="${REPO_ROOT}/skills"
AGENTS_FILE="${REPO_ROOT}/AGENTS.md"
MANIFEST="${REPO_ROOT}/.superpowers/manifest.json"
OVERLAY="${REPO_ROOT}/.superpowers/overlay"
UPSTREAM_URL="${SUPERPOWERS_REPO:-https://github.com/obra/superpowers}"

REF="${SUPERPOWERS_REF:-v7.0.0}"
SOURCE_DIR=""
MODE="install"
WRITE_AGENTS=1

while [ $# -gt 0 ]; do
  case "$1" in
    --check) MODE="check"; shift ;;
    --ref) REF="$2"; shift 2 ;;
    --source) SOURCE_DIR="$2"; shift 2 ;;
    --no-agents) WRITE_AGENTS=0; shift ;;
    -h|--help) sed -n '2,18p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

say() { printf '  %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

command -v python3 >/dev/null || die "python3 is required"

render_tree() { # <upstream_skills_dir> <out_skills_dir>  — vendor + overlay + pointer
  local src="$1" out="$2"
  rm -rf "$out"
  mkdir -p "$out"
  cp -R "${src}/." "$out/"
  if [ -d "${OVERLAY}/skills" ]; then
    cp -R "${OVERLAY}/skills/." "$out/"
  fi
  python3 - "$out/using-superpowers/SKILL.md" <<'PY'
import sys
path = sys.argv[1]
text = open(path, encoding="utf-8").read()
pointer = "- Arena Agent Mode: `references/arena-agent-mode-tools.md`\n"
if pointer not in text:
    anchor = "- Muse: `references/muse-tools.md`\n"
    if anchor in text:
        text = text.replace(anchor, anchor + pointer, 1)
    else:  # anchor moved upstream — append to the Platform Adaptation list
        marker = "## User Instructions"
        text = text.replace(marker, pointer + "\n" + marker, 1)
    open(path, "w", encoding="utf-8").write(text)
PY
}

render_agents_block() { # <out_file>  — write the bootstrap + index inside the markers
  python3 - "$REPO_ROOT" "$REF" "$OUT_COMMIT" "$OUT_VERSION" "$OUT_DATE" > "$1" <<'PY'
import hashlib, re, sys, glob, os

repo, ref, commit, version, date = sys.argv[1:6]
skills = os.path.join(repo, "skills")

def read(p):
    with open(p, encoding="utf-8") as fh:
        return fh.read()

def strip_frontmatter(text):
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            return text[end + 5:].lstrip("\n")
    return text

def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    data = {}
    if m:
        for line in m.group(1).splitlines():
            if ":" in line and not line.startswith((" ", "\t")):
                k, v = line.split(":", 1)
                data[k.strip()] = v.strip().strip('"').strip("'")
    return data

skill_files = sorted(glob.glob(os.path.join(skills, "*", "SKILL.md")))
index_lines = []
for path in skill_files:
    meta = frontmatter(read(path))
    name = meta.get("name") or os.path.basename(os.path.dirname(path))
    desc = meta.get("description") or "(no description)"
    index_lines.append(f"- **{name}** — {desc}")

bootstrap = strip_frontmatter(read(os.path.join(skills, "using-superpowers", "SKILL.md")))
mapping = read(os.path.join(skills, "using-superpowers", "references", "arena-agent-mode-tools.md"))

print(f"""<!-- BEGIN superpowers (generated by scripts/superpowers-install.sh - do not edit inside these markers) -->
# Superpowers ({version}, installed {date}, ref `{ref}`, commit `{commit[:10]}`)

<EXTREMELY_IMPORTANT>
You have superpowers.

This repository has the official **Superpowers** skills by obra (Jesse Vincent)
installed: an agentic skills framework and software development methodology.
Their rules are mandatory, not suggestions.

The full content of the `using-superpowers` skill is below - it is your
introduction to using skills and it is already loaded; do not try to load it
again. For every other skill, this harness has no skill tool: **read
`skills/<skill-name>/SKILL.md` with `read_file`** when the skill applies. That
read *is* this harness's skill-loading mechanism. Do this before any response or
action, including clarifying questions.

The harness tool mapping and the index of installed skills follow.

---

{bootstrap.strip()}

---

## Arena Agent Mode tool mapping

{mapping.strip()}

---

## Installed skills

Load any of these by reading its `SKILL.md` (descriptions are the trigger
conditions; `skills/*/SKILL.md` frontmatter is the authoritative list):

{chr(10).join(index_lines)}
</EXTREMELY_IMPORTANT>
<!-- END superpowers -->""")
PY
}

splice_agents_file() { # <rendered_block_file>
  python3 - "$AGENTS_FILE" "$1" <<'PY'
import sys
target, block_file = sys.argv[1:3]
block = open(block_file, encoding="utf-8").read().rstrip("\n")
starter = "# AGENTS.md\n\nGuidance for AI coding agents working in this repository.\n\n"
try:
    with open(target, encoding="utf-8") as fh:
        current = fh.read()
except FileNotFoundError:
    current = starter
begin = "<!-- BEGIN superpowers"
end = "<!-- END superpowers -->"
if begin in current and end in current:
    head = current[: current.index(begin)]
    tail = current[current.index(end) + len(end):]
    new = head.rstrip("\n") + "\n\n" + block + tail
else:
    new = current.rstrip("\n") + "\n\n" + block + "\n"
with open(target, "w", encoding="utf-8") as fh:
    fh.write(new if new.endswith("\n") else new + "\n")
PY
}

case "$MODE" in
check)
  [ -f "$MANIFEST" ] || die "no manifest at .superpowers/manifest.json - is Superpowers installed?"
  [ -d "$SKILLS_DIR" ] || die "no skills/ directory"
  python3 - "$REPO_ROOT" "$MANIFEST" "$AGENTS_FILE" <<'PY'
import hashlib, json, os, sys
repo, manifest_path, agents = sys.argv[1:4]
man = json.load(open(manifest_path, encoding="utf-8"))
problems, checked = [], 0
for rel, digest in man.get("files", {}).items():
    path = os.path.join(repo, rel)
    if not os.path.isfile(path):
        problems.append(f"missing: {rel}")
        continue
    actual = hashlib.sha256(open(path, "rb").read()).hexdigest()
    checked += 1
    if actual != digest:
        problems.append(f"modified since install: {rel}")
print(f"  files recorded: {len(man.get('files', {}))}, verified: {checked}")
print(f"  upstream: {man.get('upstream')} @ {man.get('ref')} ({man.get('version')}, {man.get('commit','')[:10]})")
if agents:
    text = open(agents, encoding="utf-8").read() if os.path.isfile(agents) else ""
    begin, end = "<!-- BEGIN superpowers", "<!-- END superpowers -->"
    if begin not in text or end not in text:
        problems.append("AGENTS.md is missing the superpowers bootstrap block")
    else:
        block = text[text.index(begin): text.index(end) + len(end)]
        got = hashlib.sha256(block.encode()).hexdigest()
        if got != man.get("bootstrap_sha256"):
            problems.append("AGENTS.md bootstrap block differs from the generated one (re-run the installer)")
        else:
            print("  AGENTS.md bootstrap: matches generated content")
    found = {os.path.basename(os.path.dirname(p)) for p in
             __import__("glob").glob(os.path.join(repo, "skills", "*", "SKILL.md"))}
    index_text = text[text.index(begin):] if begin in text else ""
    missing = sorted(s for s in found if f"**{s}**" not in index_text)
    if missing:
        problems.append("skills missing from the AGENTS.md index: " + ", ".join(missing))
    elif found:
        print(f"  skills indexed: {len(found)}")
if problems:
    print("\nFAILED:")
    for p in problems:
        print(f"  - {p}")
    raise SystemExit(1)
print("\nOK: install verified")
PY
  ;;
install)
  echo "Installing Superpowers (${REF}) into ${REPO_ROOT}"
  TMP=""
  if [ -n "$SOURCE_DIR" ]; then
    SRC="$SOURCE_DIR"
    [ -d "${SRC}/skills" ] || die "--source must point at a superpowers checkout (no skills/ found)"
    say "source: ${SRC}"
  else
    TMP="$(mktemp -d)"
    trap 'rm -rf "$TMP"' EXIT
    say "cloning ${UPSTREAM_URL} @ ${REF}"
    git clone --quiet --depth 1 --branch "$REF" "$UPSTREAM_URL" "${TMP}/superpowers" 2>/dev/null \
      || { git clone --quiet "$UPSTREAM_URL" "${TMP}/superpowers" && git -C "${TMP}/superpowers" checkout --quiet "$REF"; }
    SRC="${TMP}/superpowers"
  fi
  say "vendoring skills/ (verbatim + local overlay)"
  render_tree "${SRC}/skills" "$SKILLS_DIR"
  if [ -f "${SRC}/LICENSE" ]; then
    cp "${SRC}/LICENSE" "${REPO_ROOT}/.superpowers/UPSTREAM-LICENSE"
  fi
  OUT_COMMIT="$(git -C "$SRC" rev-parse HEAD 2>/dev/null || echo unknown)"
  OUT_VERSION="$(python3 - "$SRC" "$SKILLS_DIR" <<'PY'
import json, os, re, sys
src, skills = sys.argv[1:3]
for candidate in (os.path.join(src, ".claude-plugin", "plugin.json"), os.path.join(src, "package.json")):
    if os.path.isfile(candidate):
        try:
            print(json.load(open(candidate))["version"]); raise SystemExit
        except (KeyError, ValueError):
            pass
text = open(os.path.join(skills, "using-superpowers", "SKILL.md"), encoding="utf-8").read()
m = re.search(r"version:\s*([0-9][^\s]*)", text)
print(m.group(1) if m else "unknown")
PY
)"
  OUT_DATE="$(date -u +%Y-%m-%d)"

  if [ "$WRITE_AGENTS" = "1" ]; then
    say "generating AGENTS.md bootstrap (using-superpowers + tool mapping + skill index)"
    BLOCK="$(mktemp)"
    render_agents_block "$BLOCK"
    splice_agents_file "$BLOCK"
    rm -f "$BLOCK"
  fi

  say "recording .superpowers/manifest.json"
  python3 - "$REPO_ROOT" "$MANIFEST" "$UPSTREAM_URL" "$REF" "$OUT_COMMIT" "$OUT_VERSION" "$OUT_DATE" "$WRITE_AGENTS" <<'PY'
import hashlib, json, os, sys
repo, manifest_path, url, ref, commit, version, date, write_agents = sys.argv[1:9]
files = {}
for root, _dirs, names in os.walk(os.path.join(repo, "skills")):
    for name in names:
        path = os.path.join(root, name)
        rel = os.path.relpath(path, repo)
        files[rel] = hashlib.sha256(open(path, "rb").read()).hexdigest()
license_path = os.path.join(repo, ".superpowers", "UPSTREAM-LICENSE")
if os.path.isfile(license_path):
    files[".superpowers/UPSTREAM-LICENSE"] = hashlib.sha256(open(license_path, "rb").read()).hexdigest()
block_sha = None
if write_agents == "1":
    text = open(os.path.join(repo, "AGENTS.md"), encoding="utf-8").read()
    begin, end = "<!-- BEGIN superpowers", "<!-- END superpowers -->"
    if begin in text and end in text:
        block_sha = hashlib.sha256(text[text.index(begin): text.index(end) + len(end)].encode()).hexdigest()
manifest = {
    "installer": "scripts/superpowers-install.sh",
    "harness": "arena-agent-mode",
    "method": "project-scoped instructions-file (AGENTS.md) + vendored skills/",
    "upstream": url,
    "ref": ref,
    "commit": commit,
    "version": version,
    "installed_at": date,
    "skills_dir": "skills",
    "bootstrap_file": "AGENTS.md",
    "bootstrap_sha256": block_sha,
    "skill_count": sum(1 for k in files if k.endswith("SKILL.md")),
    "file_count": len(files),
    "files": dict(sorted(files.items())),
}
os.makedirs(os.path.dirname(manifest_path), exist_ok=True)
with open(manifest_path, "w", encoding="utf-8") as fh:
    json.dump(manifest, fh, indent=2)
    fh.write("\n")
print(f"  skills: {manifest['skill_count']}, files: {manifest['file_count']}")
PY
  echo "Done. Verify with: bash scripts/superpowers-install.sh --check"
  ;;
esac
