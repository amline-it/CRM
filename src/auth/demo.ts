/**
 * حالت نمایش محلی (فقط برای پیش‌نمایش روی همین ماشین).
 *
 * ⚠️ هشدار امنیتی: با فعال‌بودن این حالت، صفحه ورود غیرفعال می‌شود و هر بازدیدکننده
 * با نقش مدیر وارد پنل می‌شود. این متغیر **نباید** روی سرور واقعی تنظیم شود.
 *
 * محافظت‌های در نظر گرفته‌شده:
 *   ۱) پیش‌فرض خاموش است (فقط مقدار دقیق «true» آن را روشن می‌کند).
 *   ۲) این متغیر فقط در فایل .env.local (که در گیت نیست) تنظیم می‌شود.
 *   ۳) در docker-compose.yml صریحاً false شده تا هنگام استقرار روی سرور خاموش بماند.
 *   ۴) وضعیت روی همه صفحات پنل با یک نشان (badge) هشدار داده می‌شود.
 */
export function demoModeEnabled(): boolean {
  return (process.env.LOCAL_DEMO_MODE ?? "").trim().toLowerCase() === "true";
}

